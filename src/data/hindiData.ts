export function getHindiLetterVoiceData(letter: HindiLetter): { hindi: string; phonetic: string } {
  const hindi = `${letter.char}: ${letter.char} से ${letter.word}`;
  const phonetic = letter.phoneticPronounce || `${letter.roman.toUpperCase()}: ${letter.roman} say ${letter.wordEnglish.split('(')[0].trim()}`;
  return { hindi, phonetic };
}

